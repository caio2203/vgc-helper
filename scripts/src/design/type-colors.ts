/**
 * Generates apps/web/src/styles/type-colors.css: the 18 type colors of DESIGN.md §3.2, per theme,
 * computed in OKLCH and checked against WCAG 2.2 contrast. Run with `pnpm design:colors`.
 * Change hues or chroma here, never the CSS by hand.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../../../apps/web/src/styles/type-colors.css', import.meta.url));

/** Theme inks and surfaces from DESIGN.md §3.1. */
const THEMES = {
  light: { ink: '#17191C', surface: '#FFFFFF' },
  dark: { ink: '#EEEDE8', surface: '#191C20' },
} as const;

/** Minimum contrast: ink on the fill, and the type's text tone on the surface. */
const TARGETS = { light: { fill: 7, text: 4.6 }, dark: { fill: 5.2, text: 4.6 } } as const;

/** OKLCH hue and chroma per type, tuned so the 18 types stay distinguishable. */
const TYPES: Record<string, [hue: number, chroma: number]> = {
  Normal: [95, 0.035],
  Fire: [48, 0.17],
  Water: [252, 0.14],
  Electric: [95, 0.17],
  Grass: [142, 0.16],
  Ice: [205, 0.1],
  Fighting: [33, 0.12],
  Poison: [320, 0.16],
  Ground: [75, 0.1],
  Flying: [262, 0.07],
  Psychic: [356, 0.19],
  Bug: [122, 0.15],
  Rock: [88, 0.07],
  Ghost: [308, 0.12],
  Dragon: [281, 0.19],
  Dark: [50, 0.03],
  Steel: [230, 0.035],
  Fairy: [335, 0.08],
};

type Rgb = [number, number, number];

const toLinear = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toGamma = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

function oklchToLinearRgb(L: number, C: number, h: number): Rgb {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

/** OKLCH to sRGB, lowering chroma until the color fits the gamut. */
function oklch(L: number, C: number, h: number): Rgb {
  let chroma = C;
  let rgb = oklchToLinearRgb(L, chroma, h);
  while (rgb.some((v) => v < -1e-4 || v > 1 + 1e-4) && chroma > 0) {
    chroma -= 0.002;
    rgb = oklchToLinearRgb(L, chroma, h);
  }
  return rgb.map((v) => toGamma(Math.min(1, Math.max(0, v)))) as Rgb;
}

const toHex = (rgb: Rgb) =>
  `#${rgb
    .map((v) =>
      Math.round(v * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')
    .toUpperCase()}`;
const fromHex = (hex: string): Rgb =>
  [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16) / 255) as Rgb;
const luminance = (rgb: Rgb) => {
  const [r, g, b] = rgb.map(toLinear) as Rgb;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export function contrast(a: Rgb, b: Rgb): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

/** First lightness, walking from `from` to `to`, that reaches the target contrast. */
function solve(
  h: number,
  C: number,
  against: string,
  target: number,
  from: number,
  to: number,
): Rgb {
  const step = from < to ? 0.002 : -0.002;
  for (let L = from; from < to ? L <= to : L >= to; L += step) {
    const rgb = oklch(L, C, h);
    if (contrast(rgb, fromHex(against)) >= target) return rgb;
  }
  throw new Error(`No color reaches ${target}:1 against ${against} for hue ${h}`);
}

const lines: Record<'light' | 'dark', string[]> = { light: [], dark: [] };
const report: string[] = [];
for (const [name, [h, C]] of Object.entries(TYPES)) {
  const id = name.toLowerCase();
  const l = THEMES.light;
  const d = THEMES.dark;
  const lightFill = solve(h, C, l.ink, TARGETS.light.fill, 0.7, 0.97);
  const lightText = solve(h, C, l.surface, TARGETS.light.text, 0.75, 0.2);
  const darkFill = solve(h, C, d.ink, TARGETS.dark.fill, 0.62, 0.2);
  const darkText = solve(h, C, d.surface, TARGETS.dark.text, 0.5, 0.97);
  lines.light.push(
    `  --type-${id}-fill: ${toHex(lightFill)};`,
    `  --type-${id}-text: ${toHex(lightText)};`,
  );
  lines.dark.push(
    `  --type-${id}-fill: ${toHex(darkFill)};`,
    `  --type-${id}-text: ${toHex(darkText)};`,
  );
  report.push(
    `${name.padEnd(9)} light ${toHex(lightFill)} ${contrast(lightFill, fromHex(l.ink)).toFixed(1)}:1 · ` +
      `${toHex(lightText)} ${contrast(lightText, fromHex(l.surface)).toFixed(1)}:1   dark ${toHex(darkFill)} ` +
      `${contrast(darkFill, fromHex(d.ink)).toFixed(1)}:1 · ${toHex(darkText)} ${contrast(darkText, fromHex(d.surface)).toFixed(1)}:1`,
  );
}

const css = `/* Generated by scripts/src/design/type-colors.ts (pnpm design:colors). Do not edit by hand. */
/* fill: chip and type-edge background, text on it is --ink. text: the type color for text on --surface. */
:root {
${lines.light.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${lines.dark.map((l) => `  ${l}`).join('\n')}
  }
}

:root[data-theme="dark"] {
${lines.dark.join('\n')}
}
`;

writeFileSync(OUT, css);
console.log(report.join('\n'));
console.log(`Wrote ${OUT}`);
